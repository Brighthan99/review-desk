import { changeRuns } from './blocks';
import { filePath, type DiffFile, type DiffLine } from './diffParser';

/**
 * Changes a reviewer need not read line by line, told apart without AI: only whitespace,
 * code moved from elsewhere in the change, or import lines.
 */
export type Trivial = 'whitespace' | 'moved' | 'imports';

export const TRIVIAL_LABELS: Record<Trivial, string> = {
  whitespace: 'whitespace only',
  moved: 'moved code',
  imports: 'imports only',
};

export interface FileTrivia {
  /** Per change block, in `changeBlocks` order: what makes it trivial, if anything. */
  blocks: (Trivial | undefined)[];
  /** Set when the whole file needs no reading: generated, renamed only, or every block trivial. */
  label?: string;
}

/** Lock files and build outputs, by path. */
const GENERATED_PATH =
  /(^|\/)(package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Cargo\.lock|poetry\.lock|uv\.lock|Pipfile\.lock|go\.sum|composer\.lock|Gemfile\.lock|Podfile\.lock|flake\.lock|packages\.lock\.json)$|\.(min\.js|min\.css|js\.map|css\.map|snap|pb\.go|g\.dart|freezed\.dart|designer\.cs)$|_pb2(_grpc)?\.pyi?$|(^|\/)__snapshots__\//;
/** A header saying the file is generated, in its first lines. */
const GENERATED_HEADER = /@generated|\bDO NOT EDIT\b|\bauto-?generated\b|\bgenerated by\b/i;

/** Lock files and other generated files, by path: noise for the agent, often the bulk of a diff. */
export function isGenerated(path: string): boolean {
  return GENERATED_PATH.test(path);
}

const IMPORT_LINE =
  /^\s*(import\b|export\s+(\*|type\s+\{|\{)[^;]*\bfrom\b|from\s+[\w.]+\s+import\b|#\s*include\b|#\s*import\b|using\s+(static\s+)?[\w.]+\s*;|use\s+[\w:{}, *]+;|(const|let|var)\s+[\w{}\s,:]+=\s*require\(|require(_relative)?[\s(]+['"]|package\s+[\w.]+;?\s*$)/;
/** A line inside a multi-line import list: a name, or the closing `} from '…'`. */
const IMPORT_PART = /^\s*([\w$]+(\s+as\s+[\w$]+)?,?|\}\s*(from\s+\S+)?\s*;?|\)\s*;?)\s*$/;

const key = (l: DiffLine) => l.text.trim();
const significant = (text: string) => text.length >= 6 && /[A-Za-z0-9]/.test(text);

function count(map: Map<string, number>, lines: DiffLine[], by = 1): void {
  for (const l of lines) {
    const k = key(l);
    if (k) map.set(k, (map.get(k) ?? 0) + by);
  }
}

/**
 * What needs no line-by-line reading in each file of a change. Moved code is matched across
 * the whole change: a block whose lines were all deleted (or added) elsewhere.
 */
export function classifyChange(files: DiffFile[]): Map<string, FileTrivia> {
  const runs = new Map(files.map((f) => [f, f.binary ? [] : changeRuns(f)]));
  const addedAll = new Map<string, number>();
  const deletedAll = new Map<string, number>();
  for (const list of runs.values()) {
    for (const r of list) {
      count(addedAll, r.added);
      count(deletedAll, r.deleted);
    }
  }
  const out = new Map<string, FileTrivia>();
  for (const [file, list] of runs) {
    const blocks = list.map((r) => classifyRun(r, addedAll, deletedAll));
    out.set(filePath(file), { blocks, label: fileLabel(file, blocks) });
  }
  return out;
}

function classifyRun(
  run: { added: DiffLine[]; deleted: DiffLine[] },
  addedAll: Map<string, number>,
  deletedAll: Map<string, number>,
): Trivial | undefined {
  const squash = (lines: DiffLine[]) => lines.map((l) => l.text.replace(/\s+/g, '')).join('');
  if (squash(run.added) === squash(run.deleted)) return 'whitespace';

  const changed = [...run.added, ...run.deleted].filter((l) => key(l));
  if (
    changed.some((l) => IMPORT_LINE.test(l.text)) &&
    changed.every((l) => IMPORT_LINE.test(l.text) || IMPORT_PART.test(l.text))
  ) {
    return 'imports';
  }

  // Moved: every line found on the other side somewhere else in the change.
  if (changed.length < 3 || !changed.some((l) => significant(key(l)))) return undefined;
  const own = (lines: DiffLine[]) => {
    const m = new Map<string, number>();
    count(m, lines);
    return m;
  };
  const ownAdded = own(run.added);
  const ownDeleted = own(run.deleted);
  const elsewhere = (all: Map<string, number>, mine: Map<string, number>, k: string) =>
    (all.get(k) ?? 0) - (mine.get(k) ?? 0) > 0;
  const moved =
    run.added.every((l) => !key(l) || elsewhere(deletedAll, ownDeleted, key(l))) &&
    run.deleted.every((l) => !key(l) || elsewhere(addedAll, ownAdded, key(l)));
  return moved ? 'moved' : undefined;
}

function fileLabel(file: DiffFile, blocks: (Trivial | undefined)[]): string | undefined {
  if (isGenerated(filePath(file))) return 'generated';
  const head = file.hunks
    .flatMap((h) => h.lines)
    .filter((l) => l.kind !== 'del' && l.newLine !== null && l.newLine <= 5);
  if (head.some((l) => GENERATED_HEADER.test(l.text))) return 'generated';
  if (file.binary) return undefined;
  if (!blocks.length) return file.status === 'renamed' ? 'renamed only' : undefined;
  if (blocks.some((b) => !b)) return undefined;
  return [...new Set(blocks as Trivial[])].map((t) => TRIVIAL_LABELS[t]).join(', ');
}

const cache = new WeakMap<object, Map<string, FileTrivia>>();

/** `classifyChange` of a review target's files, worked out once per target. */
export function triviaOf(target: { files: DiffFile[] }): Map<string, FileTrivia> {
  let trivia = cache.get(target);
  if (!trivia) {
    trivia = classifyChange(target.files);
    cache.set(target, trivia);
  }
  return trivia;
}
