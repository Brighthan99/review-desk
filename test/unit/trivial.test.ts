import { describe, expect, it } from 'vitest';
import { parseUnifiedDiff } from '../../src/review/diffParser';
import { classifyChange } from '../../src/review/trivial';

const file = (path: string, body: string[], header = '') =>
  `diff --git a/${path} b/${path}\n${header}--- a/${path}\n+++ b/${path}\n${body.join('\n')}\n`;

const classify = (...files: string[]) => classifyChange(parseUnifiedDiff(files.join('')));

describe('classifyChange', () => {
  it('tells whitespace-only blocks, including blank lines added', () => {
    const t = classify(
      file('a.ts', [
        '@@ -1,4 +1,5 @@',
        ' function f() {',
        '-  return 1;',
        '+    return 1;',
        ' }',
        '+',
        ' const x = 2;',
      ]),
    );
    expect(t.get('a.ts')).toEqual({
      blocks: ['whitespace', 'whitespace'],
      label: 'whitespace only',
    });
  });

  it('tells import-only blocks, also multi-line import lists', () => {
    const t = classify(
      file('a.ts', [
        '@@ -1,3 +1,7 @@',
        "-import { a } from './a';",
        '+import {',
        '+  a,',
        '+  b,',
        "+} from './a';",
        "+import type { C } from './c';",
        ' ',
        ' export const x = a();',
      ]),
      file('b.py', ['@@ -1,2 +1,3 @@', ' import os', '+from typing import List', ' x = 1']),
    );
    expect(t.get('a.ts')).toEqual({ blocks: ['imports'], label: 'imports only' });
    expect(t.get('b.py')?.blocks).toEqual(['imports']);
  });

  it('tells code moved from one file to another, and not code merely edited', () => {
    const t = classify(
      file('a.ts', [
        '@@ -1,6 +1,2 @@',
        ' const keep = 1;',
        '-export function total(items: Item[]): number {',
        '-  return items.reduce((s, i) => s + i.price, 0);',
        '-}',
        '-',
        ' const more = 2;',
      ]),
      file('b.ts', [
        '@@ -1,2 +1,5 @@',
        ' const other = 1;',
        '+export function total(items: Item[]): number {',
        '+  return items.reduce((s, i) => s + i.price, 0);',
        '+}',
      ]),
      file('c.ts', [
        '@@ -1,3 +1,3 @@',
        ' a();',
        '-const limit = 10;',
        '+const limit = 20;',
        ' b();',
      ]),
    );
    expect(t.get('a.ts')).toEqual({ blocks: ['moved'], label: 'moved code' });
    expect(t.get('b.ts')).toEqual({ blocks: ['moved'], label: 'moved code' });
    expect(t.get('c.ts')).toEqual({ blocks: [undefined], label: undefined });
  });

  it('labels a file trivial only when every block is, naming each kind', () => {
    const t = classify(
      file('a.ts', [
        '@@ -1,6 +1,7 @@',
        "+import { b } from './b';",
        ' function f() {',
        '-  return 1;',
        '+    return 1;',
        ' }',
        '-const x = 1;',
        '+const x = 2;',
        ' end();',
      ]),
      file('b.ts', [
        '@@ -1,3 +1,4 @@',
        "+import { b } from './b';",
        ' function f() {',
        '-  return 1;',
        '+    return 1;',
      ]),
    );
    expect(t.get('a.ts')?.label).toBeUndefined();
    expect(t.get('b.ts')?.label).toBe('imports only, whitespace only');
  });

  it('labels generated files, by path or by their header, and renames without edits', () => {
    const t = classify(
      file('package-lock.json', ['@@ -1,1 +1,1 @@', '-{"a":1}', '+{"a":2}']),
      file(
        'api/user.pb.ts',
        ['@@ -0,0 +1,2 @@', '+// Code generated by protoc-gen-ts. DO NOT EDIT.', '+export {};'],
        'new file mode 100644\n',
      ),
      'diff --git a/old.ts b/new.ts\nsimilarity index 100%\nrename from old.ts\nrename to new.ts\n',
    );
    expect(t.get('package-lock.json')?.label).toBe('generated');
    expect(t.get('api/user.pb.ts')?.label).toBe('generated');
    expect(t.get('new.ts')?.label).toBe('renamed only');
  });
});
